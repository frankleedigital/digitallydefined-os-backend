/** A DB whose env var is empty/unset resolves to null (callers skip it). */
export function getNotionDbId(key) {
  const spec = NOTION_OS_DBS[key];
  if (!spec) return null;
  // Accept the canonical env var first, then any documented aliases so the
  // contract and a deployed environment can disagree on the name without
  // silently resolving to null (which would skip the DB).
  for (const name of [spec.envVar, ...(spec.envVarAliases || [])]) {
    const raw = process.env[name];
    if (raw && String(raw).trim()) return String(raw).trim();
  }
  return null;
}

/** The live Notion property name for an architect property (DB-wins mapping). */
export function notionPropName(prop) {
  // After the rename run, notionName === canonical name for these DBs.
  return prop?.name || null;
}

/** Legacy names still accepted on input during/after a rename transition. */
export function legacyPropNames(prop) {
  const out = [];
  if (prop?.notionName && prop.notionName !== prop?.name) out.push(prop.notionName);
  for (const n of (prop?.legacyNames || [])) {
    if (n && n !== prop?.name && !out.includes(n)) out.push(n);
  }
  return out;
}

/**
 * Resolve an architect property name (e.g. 'Name', 'Signal') to the name the
 * property actually carries in the live Notion database (e.g. 'Month',
 * 'Sentiment'). Returns null for an unknown DB/property.
 */
export function getNotionPropName(dbKey, propName) {
  const spec = NOTION_OS_DBS[dbKey];
  const prop = spec?.properties.find((p) => p.name === propName);
  return prop ? notionPropName(prop) : null;
}

/** The DB's title property: architect name + live Notion name. */
export function getNotionTitleProp(dbKey) {
  const spec = NOTION_OS_DBS[dbKey];
  const prop = spec?.properties.find((p) => p.type === 'title');
  return prop
    ? { architectName: prop.name, notionName: notionPropName(prop), readOnly: !!prop.readOnly }
    : null;
}

/**
 * Properties the Architect is allowed to write. Excludes read-only fields such
 * as Notion's auto-generated created_time, which the API rejects on write.
 */
export function getWritableNotionProps(dbKey) {
  const spec = NOTION_OS_DBS[dbKey];
  if (!spec) return [];
  return spec.properties.filter((p) => !p.readOnly);
}

export function listNotionDbIds() {
  const out = {};
  for (const key of Object.keys(NOTION_OS_DBS)) out[key] = getNotionDbId(key);
  return out;
}

/** Unified schema map for all 8 DBs (with env-resolved IDs). */
export function getNotionSchemaMap() {
  const out = {};
  for (const [key, spec] of Object.entries(NOTION_OS_DBS)) {
    out[key] = {
      key: spec.key,
      label: spec.label,
      envVar: spec.envVar,
      dbId: getNotionDbId(key),
      dedupKeys: spec.dedupKeys.map((k) => getNotionPropName(key, k) || k),
      syncSafeKeys: spec.properties.map((p) => notionPropName(p)),
      notionNames: spec.properties.map((p) => ({ architectName: p.name, notionName: notionPropName(p), readOnly: !!p.readOnly })),
      properties: spec.properties,
    };
  }
  return out;
}

/**
 * Reverse lookup: which architect DB key owns this databaseId?
 * Enables callers that only have a raw Notion database ID (e.g. an existing
 * lib/antigravity.js call site) to still get spec-driven behaviour.
 * Returns null when the ID isn't one of the 8 architect DBs.
 */
export function resolveDbKeyForId(databaseId) {
  if (!databaseId) return null;
  const target = String(databaseId).trim();
  for (const key of Object.keys(NOTION_OS_DBS)) {
    if (getNotionDbId(key) === target) return key;
  }
  return null;
}

