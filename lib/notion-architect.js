/**
 * One-shot: normalize → validate → build Notion properties for a page create.
 * This is the single entry point write callers should use so that the
 * normalize/clamp/synonym rules can never be skipped.
 *
 * Accepts free-form property input (e.g. from an LLM proposal) and returns
 * either { ok: true, properties } or { ok: false, error }.
 *
 * @param {string} dbKey   architect DB key
 * @param {object} input   free-form record, e.g. { Name, Status:'live', Niche, Revenue:'1200' }
 */
export function buildValidatedPageProperties(dbKey, input) {
  const spec = NOTION_OS_DBS[dbKey];
  if (!spec) return { ok: false, error: `Unknown architect DB key: ${dbKey}`, properties: null, record: null };

  const record = normalizeNotionRecord(dbKey, input || {});
  const validation = validateNotionRecord(dbKey, record);
  if (!validation.valid) {
    return { ok: false, error: validation.error, properties: null, record };
  }
  return { ok: true, error: null, properties: buildNotionProperties(dbKey, record), record };
}

/** Split a long string into Notion-safe rich_text chunks (2000-char API limit). */
export function chunkRichText(text, size = 2000) {
  const str = String(text ?? '');
  if (!str) return [];
  const chunks = [];
  for (let i = 0; i < str.length; i += size) chunks.push(str.slice(i, i + size));
  return chunks.slice(0, 100);
}

/**
 * Build Notion page `children` blocks from plain text.
 * Notion caps a single rich_text object at 2000 chars, so long content is
 * split into multiple paragraph blocks rather than silently rejected.
 */
export function buildPageChildren(text) {
  const chunks = chunkRichText(text, 2000);
  return chunks.map((content) => ({
    object: 'block',
    type: 'paragraph',
    paragraph: { rich_text: [{ type: 'text', text: { content } }] },
  }));
}

